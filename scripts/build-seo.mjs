function galleryLd(page) {
  return {
    '@context': 'https://schema.org',
    '@type': 'ImageGallery',
    name: page.title,
    description: page.description,
    url: `${ORIGIN}${page.path}`,
    isPartOf: { '@type': 'WebSite', name: 'vasosofuji', url: `${ORIGIN}/` },
    author: { '@id': `${ORIGIN}/#person` },
  };
}

function headBlock(page) {
  const url = `${ORIGIN}${page.path === '/' ? '/' : page.path}`;
  const ld = [];
  if (page.file === 'index.html') ld.push(siteLd, personLd, businessLd);
  if (['gallery.html', 'portraits.html', 'concerts.html', 'landscapes.html'].includes(page.file)) {
    ld.push(galleryLd(page));
  }

  const lines = [
    START,
    `    <meta name="description" content="${esc(page.description)}">`,
    `    <meta name="author" content="${AUTHOR}">`,
    page.noindex
      ? '    <meta name="robots" content="noindex, follow">'
      : '    <meta name="robots" content="index, follow, max-image-preview:large">',
    `    <link rel="canonical" href="${url}">`,
    '',
    `    <meta property="og:type" content="${page.type || 'website'}">`,
    `    <meta property="og:site_name" content="vasosofuji">`,
    `    <meta property="og:title" content="${esc(page.title)}">`,
    `    <meta property="og:description" content="${esc(page.description)}">`,
    `    <meta property="og:url" content="${url}">`,
    `    <meta property="og:image" content="${OG_IMAGE}">`,
    `    <meta property="og:image:width" content="${OG_IMAGE_W}">`,
    `    <meta property="og:image:height" content="${OG_IMAGE_H}">`,
    `    <meta property="og:image:alt" content="${esc(AUTHOR)} — photographer, Skopje">`,
    `    <meta property="og:locale" content="en_US">`,
    `    <meta property="og:locale:alternate" content="mk_MK">`,
    '',
    `    <meta name="twitter:card" content="summary_large_image">`,
    `    <meta name="twitter:title" content="${esc(page.title)}">`,
    `    <meta name="twitter:description" content="${esc(page.description)}">`,
    `    <meta name="twitter:image" content="${OG_IMAGE}">`,
  ];

  for (const obj of ld) {
    lines.push('', `    <script type="application/ld+json">${JSON.stringify(obj)}</script>`);
  }
  lines.push(END);
  return lines.join('\n');
}

let touched = 0;
for (const page of PAGES) {
  const file = join(ROOT, page.file);
  let html;
  try {
    html = await readFile(file, 'utf8');
  } catch {
    console.warn(`skip ${page.file} (not found)`);
    continue;
  }

  // Title: one per page, replacing whatever is there.
  html = html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${esc(page.title)}</title>`);

  // Remove any previously generated block FIRST. Doing it in this order keeps
  // the script idempotent: the strip below would otherwise gut the existing
  // block's own tags, and if the re-insert then failed the page would be left
  // with no description or canonical at all.
  html = html.replace(new RegExp(`\\n?${escRe(START)}[\\s\\S]*?${escRe(END)}`), '');

  // Drop any hand-written tags this block now owns, so nothing is declared twice.
  html = html
    .replace(/^[ \t]*<meta\s+name="description"[^>]*>\s*\n/gim, '')
    .replace(/^[ \t]*<meta\s+property="og:[^"]*"[^>]*>\s*\n/gim, '')
    .replace(/^[ \t]*<meta\s+name="twitter:[^"]*"[^>]*>\s*\n/gim, '')
    .replace(/^[ \t]*<link\s+rel="canonical"[^>]*>\s*\n/gim, '')
    .replace(/^[ \t]*<link\s+rel="image_src"[^>]*>\s*\n/gim, '');

  html = html.replace(/<\/title>/i, `</title>\n${headBlock(page)}`);

  await writeFile(file, html);
  touched++;
}

// ── sitemap.xml ────────────────────────────────────────────────────────────
const today = new Date().toISOString().slice(0, 10);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${PAGES.filter((p) => !p.noindex)
  .map(
    (p) => `  <url>
    <loc>${ORIGIN}${p.path}</loc>
    <lastmod>${today}</lastmod>
    <priority>${p.priority}</priority>
  </url>`
  )
  .join('\n')}
</urlset>
`;
await writeFile(join(ROOT, 'sitemap.xml'), sitemap);

// ── robots.txt ─────────────────────────────────────────────────────────────
