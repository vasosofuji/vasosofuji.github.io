const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// The markers contain regex metacharacters — "(", ")" and "." — so they must be
// escaped before going into a RegExp. Not escaping them is what made the
// re-run silently fail to match its own block.
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

